class GCN(torch.nn.Module):

    def __init__(self, input_channels, hidden_channels):

        super().__init__()

        self.conv1 = GCNConv(input_channels,hidden_channels)
        self.conv2 = GCNConv(hidden_channels,hidden_channels)
        self.linear = torch.nn.Linear(hidden_channels,1)

    def forward(self, data):

        x = data.x
        edge_index = data.edge_index

        x = self.conv1(x, edge_index)
        x = F.relu(x)



        x = F.dropout(
            x,
            p=0.30,
            training=self.training
        )


        x = self.conv2(x, edge_index)

        x = F.relu(x)


        # Bug #4 fix: use data.batch when graphs are batched via DataLoader
        # (batch_size > 1); fall back to all-zeros only for single-graph inference.
        # Hardcoding zeros silently pools all patients' nodes into one embedding
        # when using a DataLoader with batch_size > 1.
        batch = (data.batch if (hasattr(data, 'batch') and data.batch is not None)
                 else torch.zeros(x.size(0), dtype=torch.long, device=x.device))

        # Graph Pooling because [14,hidden_layer] from 14 nodes(feature) make it [1,hidden_layer]

        x = global_mean_pool(x,batch)



        x = self.linear(x)

        x = torch.sigmoid(x)

        return x.view(-1)

