def evaluate_model(model, test_graphs, threshold):
    model.to(device).eval()
    all_probs, all_preds, all_true = [], [], []

    with torch.no_grad():
        for graph in test_graphs:
            graph = graph.to(device)
            prob  = model(graph).squeeze().item()
            pred  = 1 if prob >= threshold else 0
            all_probs.append(prob)
            all_preds.append(pred)
            all_true.append(int(graph.y.item()))

    probs = np.array(all_probs)
    preds = np.array(all_preds)
    true  = np.array(all_true)

    cm = confusion_matrix(true, preds)
    TP = cm[1,1]; FN = cm[1,0]
    TN = cm[0,0]; FP = cm[0,1]

    return {
        'Accuracy':    round(accuracy_score(true, preds), 4),
        'Precision':   round(precision_score(true, preds, zero_division=0), 4),
        'Recall':      round(recall_score(true, preds, zero_division=0), 4),
        'F1 Score':    round(f1_score(true, preds, zero_division=0), 4),
        'ROC-AUC':     round(roc_auc_score(true, probs), 4),
        'MCC':         round(matthews_corrcoef(true, preds), 4),
        'Specificity': round(TN / (TN + FP), 4) if (TN + FP) > 0 else 0,
        'FNR':         round(FN / (FN + TP), 4) if (FN + TP) > 0 else 0,
        'FPR':         round(FP / (FP + TN), 4) if (FP + TN) > 0 else 0,
        'TP': int(TP), 'TN': int(TN), 'FP': int(FP), 'FN': int(FN),
    }


