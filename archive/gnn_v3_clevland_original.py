import torch
import torch.nn.functional as F
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from torch_geometric.explain import Explainer, GNNExplainer
from torch_geometric.data import Data

DEVICE       = torch.device('cpu')
TOP_K        = 5
FEATURES     = [
    'age', 'sex', 'cp', 'trestbps', 'chol',
    'fbs', 'restecg', 'thalach', 'exang',
    'oldpeak', 'slope', 'ca', 'thal'
]
CLINICAL_TOP = [
    'age', 'trestbps', 'chol', 'thalach',
    'exang', 'oldpeak', 'ca', 'cp', 'thal'
]
N_FEATURES   = len(FEATURES)  # 13


# ─────────────────────────────────────────────────────────────
# Safe weight extraction — works for all PyG versions
# ─────────────────────────────────────────────────────────────
def get_conv1_weight(model):
    """
    GCNConv weight attribute varies by PyG version:
      Newer PyG : model.conv1.lin.weight   -> shape [hidden, in]
      Older PyG : model.conv1.weight       -> shape [hidden, in]
    This function handles both safely.
    """
    conv1 = model.conv1
    if hasattr(conv1, 'lin') and hasattr(conv1.lin, 'weight'):
        return conv1.lin.weight.detach().cpu().numpy()   # newer PyG
    elif hasattr(conv1, 'weight'):
        return conv1.weight.detach().cpu().numpy()       # older PyG
    else:
        # Fallback: use final linear layer weights
        return model.linear.weight.detach().cpu().numpy()


# ─────────────────────────────────────────────────────────────
# GNNExplainer WRAPPER
# ─────────────────────────────────────────────────────────────
class GNNExplainerWrapper(torch.nn.Module):
    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, x, edge_index):
        data       = Data(x=x, edge_index=edge_index)
        data.batch = torch.zeros(
            x.size(0), dtype=torch.long, device=x.device)
        return self.model(data)


# ─────────────────────────────────────────────────────────────
# BASELINE XAI: Ii = wi x xi
# ─────────────────────────────────────────────────────────────
def baseline_explanation(model, graph):
    model.to(DEVICE).eval()
    graph = graph.to(DEVICE)
    with torch.no_grad():
        w      = get_conv1_weight(model)       # [hidden, input]
        w      = np.abs(w).mean(axis=0)        # [input_channels]
        x      = graph.x.cpu().numpy().flatten()  # [N_FEATURES]

        # w[0] because input_channels=1 (each node has 1 feature)
        scores = float(w[0]) * np.abs(x)
        scores = scores / (scores.sum() + 1e-8)
    return scores  # [N_FEATURES]


# ─────────────────────────────────────────────────────────────
# GNNExplainer XAI
# ─────────────────────────────────────────────────────────────
def gnnexplainer_explanation(model, graph):
    model.to(DEVICE).eval()
    graph         = graph.to(DEVICE)
    wrapped_model = GNNExplainerWrapper(model).to(DEVICE)
    wrapped_model.eval()

    explainer = Explainer(
        model=wrapped_model,
        algorithm=GNNExplainer(epochs=100),
        explanation_type='model',
        node_mask_type='attributes',
        edge_mask_type='object',
        model_config=dict(
            mode='binary_classification',
            task_level='graph',
            return_type='probs',
        ),
    )
    explanation = explainer(graph.x, graph.edge_index)
    scores      = explanation.node_mask.cpu().numpy().flatten()
    scores      = scores / (scores.sum() + 1e-8)
    return scores  # [N_FEATURES]


# ─────────────────────────────────────────────────────────────
# XAI METRICS
# ─────────────────────────────────────────────────────────────

# FIX #1: Fidelity — larger prediction change when top-k features are
# masked means the explainer correctly identified influential features.
# The old code returned 1 - |change|, which rewarded explanations that
# picked UNimportant features (no change when masked). Now we return
# |change| directly: bigger drop = better explanation.
def compute_fidelity(model, graph, feature_scores, top_k=TOP_K):
    model.to(DEVICE).eval()
    graph = graph.to(DEVICE)
    with torch.no_grad():
        original_prob = model(graph).squeeze().item()
        top_indices   = np.argsort(feature_scores)[-top_k:]
        x_masked      = graph.x.clone()
        x_masked[top_indices] = 0.0
        g_masked      = graph.clone()
        g_masked.x    = x_masked
        masked_prob   = model(g_masked).squeeze().item()
    return abs(original_prob - masked_prob)  # larger drop = better


# FIX #2: Sparsity — standard convention is
# 1 - (selected_features / total_features), so a MORE concentrated
# (sparser) explanation scores HIGHER, consistent with every other
# metric here where higher = better.
def compute_sparsity(feature_scores, top_k=TOP_K):
    threshold  = np.mean(feature_scores)
    k_selected = np.sum(feature_scores > threshold)
    return 1.0 - (k_selected / N_FEATURES)


def compute_stability(model, graph, explain_fn, n_trials=5, noise_std=0.01):
    graph    = graph.to(DEVICE)
    original = explain_fn(model, graph)
    devs     = []
    for _ in range(n_trials):
        x_noisy   = graph.x + torch.randn_like(graph.x) * noise_std
        g_noisy   = graph.clone()
        g_noisy.x = x_noisy
        devs.append(np.mean(np.abs(explain_fn(model, g_noisy) - original)))
    return max(0.0, 1.0 - np.mean(devs))


def compute_fia(feature_scores, top_k=TOP_K):
    top_idx  = np.argsort(feature_scores)[-top_k:]
    top_feat = [FEATURES[i] for i in top_idx]
    matches  = len(set(top_feat) & set(CLINICAL_TOP))
    return matches / top_k, top_feat


def compute_crs(feature_scores, top_k=TOP_K):
    top_idx  = np.argsort(feature_scores)[-top_k:]
    top_feat = [FEATURES[i] for i in top_idx]
    return sum(1 for f in top_feat if f in CLINICAL_TOP) / len(top_feat)


def compute_coverage(model, graphs, explain_fn):
    valid = 0
    for g in graphs:
        try:
            s = explain_fn(model, g.to(DEVICE))
            if s is not None and len(s) == N_FEATURES:
                valid += 1
        except:
            pass
    return valid / len(graphs)


# ─────────────────────────────────────────────────────────────
# MAIN EVALUATION
# ─────────────────────────────────────────────────────────────
def evaluate_xai(model, test_graphs, n_samples=30):
    model.to(DEVICE)
    samples = test_graphs[:n_samples]
    res = {
        'Baseline':    {k:[] for k in ['fidelity','sparsity','stability','fia','crs']},
        'GNNExplainer':{k:[] for k in ['fidelity','sparsity','stability','fia','crs']},
    }

    print(f"Computing XAI metrics on {n_samples} samples...")
    print("-" * 50)

    for i, graph in enumerate(samples):
        graph = graph.to(DEVICE)
        if (i+1) % 5 == 0:
            print(f"  Sample {i+1}/{n_samples}...")

        # -- Baseline --
        try:
            b = baseline_explanation(model, graph)
            res['Baseline']['fidelity'].append(compute_fidelity(model, graph, b))
            res['Baseline']['sparsity'].append(compute_sparsity(b))
            res['Baseline']['stability'].append(
                compute_stability(model, graph, baseline_explanation))
            fia, _ = compute_fia(b)
            res['Baseline']['fia'].append(fia)
            res['Baseline']['crs'].append(compute_crs(b))
        except Exception as e:
            print(f"  Baseline error sample {i}: {e}")

        # -- GNNExplainer --
        try:
            g = gnnexplainer_explanation(model, graph)
            res['GNNExplainer']['fidelity'].append(compute_fidelity(model, graph, g))
            res['GNNExplainer']['sparsity'].append(compute_sparsity(g))
            res['GNNExplainer']['stability'].append(
                compute_stability(model, graph, gnnexplainer_explanation))
            fia, _ = compute_fia(g)
            res['GNNExplainer']['fia'].append(fia)
            res['GNNExplainer']['crs'].append(compute_crs(g))
        except Exception as e:
            print(f"  GNNExplainer error sample {i}: {e}")

    b_cov = compute_coverage(model, samples, baseline_explanation)
    g_cov = compute_coverage(model, samples, gnnexplainer_explanation)

    def avg(lst): return round(np.mean(lst), 4) if lst else 0.0

    b_fid,b_spa,b_sta = avg(res['Baseline']['fidelity']),avg(res['Baseline']['sparsity']),avg(res['Baseline']['stability'])
    b_fia,b_crs       = avg(res['Baseline']['fia']),avg(res['Baseline']['crs'])
    b_ti              = round((b_fid+b_sta+b_crs)/3, 4)

    g_fid,g_spa,g_sta = avg(res['GNNExplainer']['fidelity']),avg(res['GNNExplainer']['sparsity']),avg(res['GNNExplainer']['stability'])
    g_fia,g_crs       = avg(res['GNNExplainer']['fia']),avg(res['GNNExplainer']['crs'])
    g_ti              = round((g_fid+g_sta+g_crs)/3, 4)

    names  = ['Fidelity','Sparsity','Stability',
              'Feature Importance Accuracy','Clinical Relevance Score',
              'Explanation Coverage','Trustworthiness Index']
    b_vals = [b_fid,b_spa,b_sta,b_fia,b_crs,round(b_cov,4),b_ti]
    g_vals = [g_fid,g_spa,g_sta,g_fia,g_crs,round(g_cov,4),g_ti]

    # FIX #3: sparsity now follows "higher = better" like every other
    # metric, so the special-cased comparison for index 1 is removed.
    winners = ['GNNExplainer' if g > b else 'Baseline' for b, g in zip(b_vals, g_vals)]

    df = pd.DataFrame({'Metric':names,'Baseline':b_vals,
                       'GNNExplainer':g_vals,'Better Method':winners})

    print("\n"+"="*70)
    print("  XAI COMPARISON: Baseline vs GNNExplainer")
    print("="*70)
    print(f"\n{'Metric':<30} {'Baseline':>10} {'GNNExplainer':>14} {'Winner':>14}")
    print("-"*70)
    for _,row in df.iterrows():
        print(f"  {row['Metric']:<28} {row['Baseline']:>10.4f} "
              f"{row['GNNExplainer']:>14.4f} {row['Better Method']:>14}")

    return df, res


