# HELPER 3: Rebuild graph list with new edge_index
# ─────────────────────────────────────────────────────────────
def rebuild_graphs(graphs, new_edge_index):
    rebuilt = []
    for g in graphs:
        new_g            = Data()
        new_g.x          = g.x
        new_g.edge_index = new_edge_index.clone()
        new_g.y          = g.y
        rebuilt.append(new_g)
    return rebuilt


# ─────────────────────────────────────────────────────────────
# HELPER 4: Build edge_index with or without MST
# ─────────────────────────────────────────────────────────────
def build_edge_index(corr_matrix, features, use_mst=True, threshold=0.15):

    # Safety check
    assert corr_matrix.shape[0] == len(features), \
        f"Mismatch: corr_matrix has {corr_matrix.shape[0]} rows but features has {len(features)}"
    assert list(corr_matrix.columns) == features, \
        f"Column order mismatch.\nCorr: {list(corr_matrix.columns)}\nFeatures: {features}"

    G = nx.Graph()
    G.add_nodes_from(features)

    for i in range(len(features)):
        for j in range(i+1, len(features)):
            if abs(corr_matrix.iloc[i, j]) >= threshold:
                G.add_edge(features[i], features[j])

    if use_mst:
        G_complete = nx.Graph()
        for i in range(len(features)):
            for j in range(i+1, len(features)):
                G_complete.add_edge(
                    features[i], features[j],
                    weight=1 - abs(corr_matrix.iloc[i, j]))
        mst = nx.minimum_spanning_tree(G_complete)
        for u, v in mst.edges():
            if not G.has_edge(u, v):
                G.add_edge(u, v)

    node_list = list(G.nodes())
    edges     = list(G.edges())
    src = [node_list.index(u) for u,v in edges] + \
          [node_list.index(v) for u,v in edges]
    dst = [node_list.index(v) for u,v in edges] + \
          [node_list.index(u) for u,v in edges]

    return torch.tensor([src, dst], dtype=torch.long)


# ─────────────────────────────────────────────────────────────
# HELPER 5: Train any model variant
# ─────────────────────────────────────────────────────────────
def train_variant(model, train_graphs, val_graphs,
                  criterion, epochs=100, patience=15, lr=0.001):
    model.to(device)
    optimizer = torch.optim.Adam(
        model.parameters(), lr=lr, weight_decay=1e-4)

    best_val_loss = float('inf')
    best_wts      = None
    no_improve    = 0

    for epoch in range(epochs):
        model.train()
        for graph in train_graphs:
            graph = graph.to(device)
            optimizer.zero_grad()
            out  = model(graph)
            loss = criterion(out, graph.y.float())
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()

        model.eval()
        val_loss, n = 0, 0
        with torch.no_grad():
            for graph in val_graphs:
                graph     = graph.to(device)
                val_loss += criterion(model(graph), graph.y.float()).item()
                n        += 1

        avg_val = val_loss / max(n, 1)

        if avg_val < best_val_loss:
            best_val_loss = avg_val
            best_wts      = {k: v.clone() for k, v in model.state_dict().items()}
            no_improve    = 0
        else:
            no_improve += 1

        if (epoch + 1) % 10 == 0:
            print(f"    Epoch [{epoch+1:>3}/{epochs}]  "
                  f"Val Loss: {avg_val:.4f}")

        if no_improve >= patience:
            print(f"    Early stopping at epoch {epoch+1}")
            break

    if best_wts:
        model.load_state_dict(best_wts)
    return model


